// PC분노관리 소개 페이지: 앱의 실제 트레이 그림(Sprites.cs)을 그대로 캔버스에 그림.
// '#' = 몸, 'H' = 천사 고리, 'W' = 날개, 'E' = 악마 눈, '.' = 빈칸
(() => {
  const RABBIT = [
    ["................","................","................","................","..........#.#...","..........#.#...","..........#.#...",".........#####..",".........##.###.","...#########....","..###########...",".############...","..###########...","..##########....","..###.....##....","................"],
    ["................","................","...........#.#..","...........#.#..","...........#.#..","..........#####.","..........##.###","....#########...","...###########..","..###########...","..##########....","..#########.....",".###......##....","##.........#....","................","................"],
    ["................","...........#.#..","...........#.#..","...........#.#..","..........#####.","..........##.###","....#########...","..############..",".#############..","..###########...","###........####.","................","................","................","................","................"],
    ["................","................","................","...........#.#..","...........#.#..","...........#.#..","..........#####.","..........##.###","...##########...","..###########...",".############...","..##########....","..####....##....","..........##....","...........##...","................"],
  ];
  const ANGEL = [
    ["................","................","................",".........HHHHH..","..........#.#...","...WW.....#.#...","..WWWW....#.#...","...WWWW..#####..","....WWW..##.###.","...#########....","..###########...",".############...","..###########...","..##########....","..###.....##....","................"],
    ["................","..........HHHHH.","...........#.#..","....WW.....#.#..","...WWWW....#.#..","....WWWW..#####.",".....WWW..##.###","....#########...","...###########..","..###########...","..##########....","..#########.....",".###......##....","##.........#....","................","................"],
    ["..........HHHHH.","...........#.#..","....WW.....#.#..","...WWWW....#.#..","....WWWW..#####.",".....WWW..##.###","....#########...","..############..",".#############..","..###########...","###........####.","................","................","................","................","................"],
    ["................","................","..........HHHHH.","...........#.#..","....WW.....#.#..","...WWWW....#.#..","....WWWW..#####.",".....WWW..##.###","...##########...","..###########...",".############...","..##########....","..####....##....","..........##....","...........##...","................"],
  ];
  const DEVIL = [
    ["................","................","................","................",".#.......#...#..","###......##.##..",".#........#.#...",".#.......#####..","..#......##E###.","..##########....","..###########...","..###########...","..###########...","..##########....","..###.....##....","................"],
    ["................","................",".#........#...#.","###.......##.##.",".#.........#.#..",".#........#####.","..#.......##E###","...##########...","...###########..","..###########...","..##########....","..#########.....",".###......##....","##.........#....","................","................"],
    ["................",".#........#...#.","###.......##.##.",".#.........#.#..",".#........#####.","..#.......##E###","...##########...","..############..",".#############..","..###########...","###........####.","................","................","................","................","................"],
    ["................","................","................",".#........#...#.","###.......##.##.",".#.........#.#..",".#........#####.","..#.......##E###","...##########...","..###########...",".############...","..##########....","..####....##....","..........##....","...........##...","................"],
  ];

  // 색은 CSS 토큰에서 읽음 (style.css :root)
  const css = getComputedStyle(document.documentElement);
  const color = (name) => css.getPropertyValue(name).trim();
  const MOODS = {
    calm:   { frames: ANGEL,  name: "천사 토끼", palette: { "#": color("--sprite-angel"), H: color("--sprite-halo"), W: color("--sprite-wing") } },
    normal: { frames: RABBIT, name: "노란 토끼", palette: { "#": color("--sprite-normal") } },
    angry:  { frames: DEVIL,  name: "악마 토끼", palette: { "#": color("--sprite-devil"), E: color("--sprite-eye") } },
  };

  // 앱과 같은 규칙: 속도 4단계(SpeedRule), 분노 게이지 60%·90% (최대 FPS 30 기준)
  const fpsFor = (v) => (v < 25 ? 5 : v < 50 ? 10 : v < 75 ? 20 : 30);
  const moodFor = (v) => (v >= 90 ? "angry" : v >= 60 ? "normal" : "calm");

  function draw(canvas, mood, index) {
    const ctx = canvas.getContext("2d");
    const { frames, palette } = MOODS[mood];
    const rows = frames[index % frames.length];
    ctx.clearRect(0, 0, 16, 16);
    for (let y = 0; y < 16; y++) {
      for (let x = 0; x < 16; x++) {
        const fill = palette[rows[y][x]];
        if (fill) { ctx.fillStyle = fill; ctx.fillRect(x, y, 1, 1); }
      }
    }
  }

  const still = window.matchMedia("(prefers-reduced-motion: reduce)");
  const animated = [];   // { canvas, mood(), fps(), frame, last }

  // 첫 화면 무대: 슬라이더로 사용률 조절
  const stage = document.getElementById("stage-canvas");
  const slider = document.getElementById("cpu");
  const out = document.getElementById("cpu-out");
  const moodName = document.getElementById("mood-name");
  const moodFps = document.getElementById("mood-fps");
  if (stage && slider) {
    const state = { canvas: stage, mood: () => moodFor(+slider.value), fps: () => fpsFor(+slider.value), frame: 0, last: 0 };
    const update = () => {
      const v = +slider.value;
      out.replaceChildren(String(v), Object.assign(document.createElement("span"), { className: "unit", textContent: "%" }));
      moodName.textContent = MOODS[moodFor(v)].name;
      moodFps.textContent = `초당 ${fpsFor(v)}프레임`;
      draw(stage, moodFor(v), state.frame);
    };
    slider.addEventListener("input", update);
    update();
    animated.push(state);
  }

  // 분노 게이지 표의 작은 토끼들
  document.querySelectorAll("canvas[data-mood]").forEach((canvas) => {
    const mood = canvas.dataset.mood;
    const fps = mood === "angry" ? 30 : mood === "normal" ? 20 : 10;
    draw(canvas, mood, 0);
    animated.push({ canvas, mood: () => mood, fps: () => fps, frame: 0, last: 0 });
  });

  // 움직임 줄이기 설정이면 첫 프레임에서 멈춤
  function tick(now) {
    if (!still.matches) {
      for (const a of animated) {
        if (now - a.last >= 1000 / a.fps()) {
          a.frame = (a.frame + 1) % 4;
          a.last = now;
          draw(a.canvas, a.mood(), a.frame);
        }
      }
    }
    requestAnimationFrame(tick);
  }
  requestAnimationFrame(tick);
})();
